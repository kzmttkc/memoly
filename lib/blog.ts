// 位置づけ（2026-07-22 新設）:
//   /roumu/* は「特定の検索意図に1対1で答える」短めのLP群（キーワード起点）。
//   /blog は、Kabauの製品コンセプト「会社の規程を覚えるAI」の核にある
//   "組織の記憶・社内規程管理" というテーマを、より長めの読み物として深掘りする場所。
//   sharoushi-agent.com（一般的な労務Tips・セルフ計算ツール中心）とテーマが
//   重ならないよう、切り口を「規程そのものの運用実態（参照されない・改定履歴が
//   残らない・現場と乖離する）」というKabauならではの角度に絞る。
//
// 執筆ルール（CLAUDE.md/§11・memory 準拠）:
//   - 敬体で統一。markdown太字・絵文字・——/とても/皆さん/絶対/結論から言う、を使わない。
//   - Phase1 厳守: 社労士監修/AI社労士/法的精度の断定表現は使わない。個別助言をしない。
//   - aggregateRating等の評価系は実データが無いため持たせない（捏造禁止）。
//   - 各記事は sharoushi-agent.com の関連記事へ1本、/roumu の関連LPへ1本の
//     内部/外部リンクを持たせ、テーマクラスタとして相互リンクする。
// ============================================================================

