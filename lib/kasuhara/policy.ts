import { KASUHARA_MEASURES, type MeasureVerdict } from './measures.ts'

export interface PolicyInput {
  companyName: string
  verdicts: { n: number; verdict: MeasureVerdict }[]
}

/** 就業規則本体へ追加する条文（ガイドの規定例と同一の骨子・会社名だけ差し込む）。 */
function mainClause(company: string): string {
  return [
    '第◯条（顧客等からの著しい迷惑行為への対応）',
    `1. ${company}（以下「会社」という）は、顧客、取引先その他の関係者（以下「顧客等」という）の言動であって、社会通念上許容される範囲を超え、従業員の就業環境を害するもの（以下「カスタマーハラスメント」という）から、従業員を保護するため、必要な措置を講ずる。`,
    '2. 従業員は、業務中にカスタマーハラスメントを受けた場合、速やかに所属長または相談窓口に報告するものとする。',
    '3. 会社は、前項の報告を受けたときは、事実関係を確認のうえ、従業員を一人で対応させない、必要に応じて対応者を交代させる、犯罪に該当し得る言動については警察への通報を検討するなど、状況に応じた措置を講ずる。',
    '4. 会社は、相談したこと又は事実確認に協力したことを理由として、当該従業員に対し解雇その他不利益な取扱いを行わない。',
  ].join('\n')
}

/** 別規程（ハラスメント防止規程）側に足す、措置別の条項スニペット。
 *  文面は運用の定め（何を決めて誰に知らせるか）に限定し、新しい法的主張を足さない。 */
const MEASURE_CLAUSES: Record<number, string> = {
  1: '会社は、カスタマーハラスメントから従業員を守る方針を定め、掲示・社内通知等により従業員に周知する。',
  2: '会社は、カスタマーハラスメントが生じた場合の対処の内容をあらかじめ定め、従業員に示す。',
  3: '会社は、カスタマーハラスメントに関する相談窓口（担当部署または担当者）を定め、従業員に周知する。',
  4: '相談窓口の担当者は、相談の内容や状況に応じて適切に対応できるよう、あらかじめ定めた手順に従って受け付け、記録する。',
  5: '会社は、相談または報告を受けたときは、速やかに事実関係を確認する。',
  6: '会社は、被害を受けた従業員に対し、一人で対応させないこと、必要に応じた対応者の交代、その他の配慮の措置を講ずる。',
  7: '会社は、確認した事実関係をふまえ、同種の事案の再発防止に取り組む。',
  8: '会社は、犯罪に該当し得る言動その他悪質な事案について、警察への通報、取引の停止その他の対処方針をあらかじめ定める。',
  9: '会社は、相談者および関係者のプライバシーを保護し、相談内容を正当な理由なく他に漏らさない。',
  10: '会社は、相談したことまたは事実確認に協力したことを理由として、従業員に不利益な取扱いを行わない。',
}

/** 委任条文（本体を短く保ちたい会社向け・ガイドの規定例と同一）。 */
const DELEGATION_CLAUSE =
  '顧客等からの著しい迷惑行為（カスタマーハラスメント）への対応に関する具体的な相談窓口、対応手順その他必要な事項は、別に定めるハラスメント防止規程による。'

const CONFIRM_POINTS = [
  '相談窓口・エスカレーション先の名称を、自社の実際の体制（部署名・役職名）に置き換えること',
  '既存のハラスメント禁止条文（セクハラ・パワハラ）とは別の条文として追加し、条番号の重複や引用ずれがないか確認すること',
  '就業規則を変更する場合は、従業員代表からの意見聴取・労働基準監督署への届出・従業員への周知の手続きを経ること（常時10人以上の事業場）',
]

const DISCLAIMER =
  '本案は、公開されている規定例をもとに自社向けに組み直した下書きであり、厚生労働省の公式ひな形でも個別の法的助言でもありません。実際の条文は、専門家に確認のうえ自社の実情に合わせて調整してください。'

/** ○△×の判定から、規程追補案（プレーンテキスト）を組み立てる。 */
export function buildPolicyDraft(input: PolicyInput): string {
  const company = (input.companyName || '').trim().slice(0, 60) || '当社'
  const gaps = input.verdicts
    .filter(v => v.verdict !== 'ok')
    .map(v => v.n)
    .sort((a, b) => a - b)

  const lines: string[] = []
  lines.push(`${company} カスタマーハラスメント対応 規程追補案（2026年10月1日施行の措置義務対応）`)
  lines.push('')
  lines.push('■ 1. 就業規則本体に追加する条文')
  lines.push(mainClause(company))
  lines.push('')
  lines.push('■ 2. 条文を短くしたい場合の委任条文（1の代わりに置く）')
  lines.push(DELEGATION_CLAUSE)
  lines.push('')
  if (gaps.length > 0) {
    lines.push('■ 3. 別規程（ハラスメント防止規程）に追加する条項——診断で「なし」「不足」だった措置')
    for (const n of gaps) {
      const m = KASUHARA_MEASURES.find(x => x.n === n)
      if (!m) continue
      lines.push(`（措置${n}: ${m.title}）`)
      lines.push(MEASURE_CLAUSES[n])
    }
  } else {
    lines.push('■ 3. 診断では10措置すべてに対応する定めが見つかりました。以下の確認だけ行ってください。')
  }
  lines.push('')
  lines.push('■ 貼り付け前に確認する3点')
  for (const [i, p] of CONFIRM_POINTS.entries()) lines.push(`${i + 1}. ${p}`)
  lines.push('')
  lines.push(DISCLAIMER)
  return lines.join('\n')
}
