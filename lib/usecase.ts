// 検索意図ランディングページのデータソース（SSOT）。
// app/roumu/[slug]/page.tsx が generateStaticParams / generateMetadata で参照し、
// app/sitemap.ts が USECASE_SLUGS を map して /roumu/{slug} を全列挙する。
//
// 設計方針:
//   - 各LPは「特定の検索意図」に1対1で対応する。doorway（薄い量産ページ）にせず、
//     その意図の説明・番頭がどう解決するか・具体例・FAQ・CTA を実コンテンツで持つ。
//   - §11 禁止表現（——/とても/皆さん/絶対/結論から言う/markdown太字）を含めない。
//   - Phase1 厳守: 「社労士監修 / AI社労士 / 法的精度○点」不使用。断定的な個別助言を
//     しない。免責（一般的な情報提供であり書類作成代行ではない）を答えに織り込む。
//   - aggregateRating（レビュー星）は実データが無いため一切持たせない（捏造禁止）。
//   - 連絡先・運営はステルス運用（kzmttkc314 / KIZUNA Creation）。
//
// 【自社ドメイン一次配信（Own-Domain First）2026-07-17】
//   日次の労務記事は、まずこの自社ドメイン（/roumu/{slug}）へ一次配信する。
//   手作業で厳選した USECASE_LIST_CURATED（下）に加え、日次生成分を
//   usecase-auto.json（機械追記の SSOT）から読み込み、末尾で連結して USECASE_LIST を作る。
//   これにより roumu_own_domain.py が JSON に1件追記するたびに、ページも sitemap も自動で増える。
//   note へは全文でなく「抜粋＋この自社記事への被リンク」を二次告知として出す（降格・廃止しない）。

// 機械追記される日次生成LP（SSOT: lib/usecase-auto.json）。空配列でも安全に連結される。
import autoUseCases from './usecase-auto.json'

export type UseCaseSection = {
  /** 小見出し */
  heading: string
  /** 本文（複数段落は配列で。各要素が1段落） */
  body: string[]
}

export type UseCaseExample = {
  /** 想定の問いかけ（番頭への相談例） */
  ask: string
  /** 番頭が返す答えのイメージ（一般情報＋自社前提の補助。断定助言にしない） */
  answer: string
}

export type Faq = { q: string; a: string }

/** 記事→無料ツールへの内部リンク（PageRank還流＋読者を計装済みツール経由でsignupへ）。
 *  内容が対応する記事にだけ手動で張る（doorway量産の相互リンクにしない）。 */
export type RelatedTool = { href: string; label: string }

export type UseCase = {
  /** URLスラッグ。/roumu/{slug} */
  slug: string
  /** ページH1 */
  h1: string
  /** title用の検索意図フレーズ（狙うキーワードを自然に含める） */
  titleKeyword: string
  /** meta description（120字前後・検索語を自然に織り込む） */
  description: string
  /** リード文（H1直下・検索意図に直接答える1〜2文） */
  lead: string
  /** OGバッジ用のカテゴリ表記 */
  ogCategory: string
  /** 「この検索意図とは何か / 何に困っているか」を言語化するセクション群 */
  sections: UseCaseSection[]
  /** 番頭がどう解決するかの具体例（2〜3件） */
  examples: UseCaseExample[]
  /** FAQ（2〜3問・FAQPage構造化データ＆本文共用） */
  faqs: Faq[]
  /** 関連する無料セルフ点検ツール（内容が対応する記事にだけ設定。任意） */
  relatedTool?: RelatedTool
  /** signup CTAに付与する計測用UTMクエリ（?next=/company に & で連結する。utm_source等）。
   *  底面ファネル語の実需検証など、流入元別のCVRを分離計測したいLPにだけ設定する。任意。 */
  signupUtm?: string
  /** 一次情報コンテンツの更新日（YYYY-MM-DD）。設定すると本文に「更新日」を明示し、
   *  Article 構造化データに dateModified/datePublished を出す（GEO/AEO恒久ルール：更新日明示）。
   *  法改正の施行スケジュールなど鮮度が判断材料になるLPにだけ設定する。任意。 */
  updatedAt?: string
  /** 一次情報コンテンツの初出日（YYYY-MM-DD・任意）。未設定時は updatedAt を datePublished に流用。 */
  publishedAt?: string
}

