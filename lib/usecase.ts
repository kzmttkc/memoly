// 検索意図ランディングページのデータソース（SSOT）。
// app/roumu/[slug]/page.tsx が generateStaticParams / generateMetadata で参照し、
// app/sitemap.ts が USECASE_SLUGS を map して /roumu/{slug} を全列挙する。
//
// 設計方針:
//   - 各LPは「特定の検索意図」に1対1で対応する。doorway（薄い量産ページ）にせず、
//     その意図の説明・番頭がどう解決するか・具体例・FAQ・CTA を実コンテンツで持つ。
//   - §11 禁止表現（——/とても/皆さん/絶対/結論から言う/markdown太字）を含めない。
//   - Phase1 厳守: 「社労士監修 / AI社労士 / 法的精度○点」不使用。断定的な個別助言を
//     しない。免責（一般的な情報提供であり書類作成代行ではない）を答えに織り込む。
//   - aggregateRating（レビュー星）は実データが無いため一切持たせない（捏造禁止）。
//   - 連絡先・運営はステルス運用（kzmttkc314 / Kizuna Creation）。

export type UseCaseSection = {
  /** 小見出し */
  heading: string
  /** 本文（複数段落は配列で。各要素が1段落） */
  body: string[]
}

export type UseCaseExample = {
  /** 想定の問いかけ（番頭への相談例） */
  ask: string
  /** 番頭が返す答えのイメージ（一般情報＋自社前提の補助。断定助言にしない） */
  answer: string
}

export type Faq = { q: string; a: string }

export type UseCase = {
  /** URLスラッグ。/roumu/{slug} */
  slug: string
  /** ページH1 */
  h1: string
  /** title用の検索意図フレーズ（狙うキーワードを自然に含める） */
  titleKeyword: string
  /** meta description（120字前後・検索語を自然に織り込む） */
  description: string
  /** リード文（H1直下・検索意図に直接答える1〜2文） */
  lead: string
  /** OGバッジ用のカテゴリ表記 */
  ogCategory: string
  /** 「この検索意図とは何か / 何に困っているか」を言語化するセクション群 */
  sections: UseCaseSection[]
  /** 番頭がどう解決するかの具体例（2〜3件） */
  examples: UseCaseExample[]
  /** FAQ（2〜3問・FAQPage構造化データ＆本文共用） */
  faqs: Faq[]
}

