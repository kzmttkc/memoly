// 年5日 有給取得義務 セルフ点検 — 日付計算の純関数コア（ブラウザ内計算・サーバ送信なし）
//
//   計算精度は信用の生命線。実装した仕様は一次情報で確認済み（確認日 2026-08-12）。
//
//   一次情報: 労働基準法 第39条第7項（e-Gov 法令XMLで原文を確認）
//     「使用者は、第一項から第三項までの規定による有給休暇（…十労働日以上である労働者に
//       係るものに限る…）の日数のうち五日については、基準日（継続勤務した期間を六箇月
//       経過日から一年ごとに区分した各期間（最後に一年未満の期間を生じたときは、当該期間）
//       の初日をいう…）から一年以内の期間に、労働者ごとにその時季を定めることにより
//       与えなければならない。」
//
//   ここから確定する2つの日付（別物であり、必ず1日ずれる）:
//     - 履行期間の終期（＝年5日を取らせる期限）
//         期間は［基準日, 基準日から一年以内］。基準日を初日に算入して起算するため、
//         民法143条2項本文により「翌年の応当日の前日」に満了する。
//         例) 基準日 2025-04-01 → 履行期間 2025-04-01〜2026-03-31
//         応当日が存在しない月（2/29 起算）は同項ただし書により「その月の末日」に満了する。
//         例) 基準日 2024-02-29 → 満了 2025-02-28
//     - 次の基準日（＝次の一年間の初日）
//         条文の「一年ごとに区分した各期間の初日」。満了日の翌日にあたる。
//         例) 基準日 2025-04-01 → 次の基準日 2026-04-01
//
//   2026-08-12 の是正: Calculator.tsx が期限と次の基準日を同一式（基準日+1年）で
//   出しており、2つの履行期間が同じ日を共有していた。しかも誤りの向きが
//   「義務未達側に猶予を1日多く見せる」＝利用者が期限を1日過ぎて違反する向きだった。
//   同型の再発を止めるため、日付の意味ごとに関数を分け tests/unit/yukyu-5nichi.test.ts
//   で暦の全日走査（期限＋1日＝次の基準日）を固定した。
// ============================================================================

/** <input type="date"> の 'YYYY-MM-DD' を解釈する。ローカル正午で構築し timezone ずれを避ける。 */
export function parseDateOnly(v: string): Date | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) return null
  const [y, m, d] = v.split('-').map(Number)
  const dt = new Date(y, m - 1, d, 12, 0, 0, 0)
  return Number.isNaN(dt.getTime()) ? null : dt
}

/** 日数を足した新しい Date（入力は変更しない）。ローカル正午固定。 */
export function addDays(d: Date, n: number): Date {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate() + n, 12, 0, 0, 0)
}

/**
 * 次の基準日（＝次の一年間の初日・労基法39条7項の「一年ごとに区分した各期間の初日」）。
 *   翌年の同月同日。2/29 起算の年だけ応当日が存在せず、JS の Date は 3/1 へ繰り上がる。
 *   これは民法143条2項ただし書の満了（2/28）の翌日と一致するため、そのまま正しい。
 */
export function nextKijunbi(base: Date): Date {
  return new Date(base.getFullYear() + 1, base.getMonth(), base.getDate(), 12, 0, 0, 0)
}

/**
 * 履行期間の終期（＝年5日を取らせる期限。この日までに5日取らせる必要がある）。
 *   「基準日から一年以内の期間」の最終日＝次の基準日の前日。
 */
export function fulfillmentDeadline(base: Date): Date {
  return addDays(nextKijunbi(base), -1)
}

export function formatJp(d: Date): string {
  return `${d.getFullYear()}年${d.getMonth() + 1}月${d.getDate()}日`
}
